/**
 * The orchestra's instruments standing among the trees of the home page:
 * a cello, drums and a guitar, silhouettes the size of a tree, drawn as
 * if they had grown there: bodies drawn by hand in Figma, necks like
 * stems that curl at the top the way the f does, drums hanging from a
 * crook like berries, a cymbal on a stem leaning out. Each is a set of
 * closed outlines in ink and a few cut-outs in paper, in local units: 1 is
 * the instrument's height, the foot at the origin, y down. They are not
 * part of the skyline (what hangs over air could not be: everything under
 * the skyline is ink) but drawn over the land in their own layer.
 */

