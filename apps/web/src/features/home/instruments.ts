/**
 * Samples an SVG path of absolute M, L, H, V, C and Z commands into
 * points, one closed polygon per subpath.
 */
const samplePath = (d: string, perCurve = 16): Pt[][] => {
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  const polys: Pt[][] = [];
  let pts: Pt[] = [];
  let cur: Pt = [0, 0];
  let i = 0;
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    const c = tokens[i++];
    if (c === 'M') {
      if (pts.length > 1) polys.push(pts);
      pts = [];
      cur = [num(), num()];
      pts.push(cur);
    } else if (c === 'L') {
      cur = [num(), num()];
      pts.push(cur);
    } else if (c === 'H') {
      cur = [num(), cur[1]];
      pts.push(cur);
    } else if (c === 'V') {
      cur = [cur[0], num()];
      pts.push(cur);
    } else if (c === 'C') {
      const p1: Pt = [num(), num()];
      const p2: Pt = [num(), num()];
      const p3: Pt = [num(), num()];
      const p0 = cur;
      for (let k = 1; k <= perCurve; k++) {
        const t = k / perCurve;
        const u = 1 - t;
        pts.push([
          u * u * u * p0[0] +
            3 * u * u * t * p1[0] +
            3 * u * t * t * p2[0] +
            t * t * t * p3[0],
          u * u * u * p0[1] +
            3 * u * u * t * p1[1] +
            3 * u * t * t * p2[1] +
            t * t * t * p3[1],
        ]);
      }
      cur = p3;
    }
  }
  if (pts.length > 1) polys.push(pts);
  return polys;
};

/** Points along a cubic Bézier. */
const bezier = (p0: Pt, p1: Pt, p2: Pt, p3: Pt, n = 24): Pt[] => {
  const out: Pt[] = [];
  for (let k = 0; k <= n; k++) {
    const t = k / n;
    const u = 1 - t;
    out.push([
      u * u * u * p0[0] +
        3 * u * u * t * p1[0] +
        3 * u * t * t * p2[0] +
        t * t * t * p3[0],
      u * u * u * p0[1] +
        3 * u * u * t * p1[1] +
        3 * u * t * t * p2[1] +
        t * t * t * p3[1],
    ]);
  }
  return out;
};

/** A stroke along a path as a closed outline, its width going from `w0` to `w1`. */
const ribbon = (pts: Pt[], w0: number, w1: number): Pt[] => {
  const left: Pt[] = [];
  const right: Pt[] = [];
  const n = pts.length;
  for (let i = 0; i < n; i++) {
    const [x0, y0] = pts[Math.max(0, i - 1)];
    const [x1, y1] = pts[Math.min(n - 1, i + 1)];
    const dx = x1 - x0;
    const dy = y1 - y0;
    const l = Math.hypot(dx, dy) || 1;
    const nx = -dy / l;
    const ny = dx / l;
    const w = w0 + (w1 - w0) * (i / (n - 1));
    left.push([pts[i][0] + (nx * w) / 2, pts[i][1] + (ny * w) / 2]);
    right.push([pts[i][0] - (nx * w) / 2, pts[i][1] - (ny * w) / 2]);
  }
  return left.concat(right.reverse());
};

/** A curl: a spiral winding in from radius `r0` over `turns`, tightening by `b` per radian. */
const spiral = (
  cx: number,
  cy: number,
  r0: number,
  turns: number,
  b: number,
  dir: 1 | -1,
  start: number,
  steps = 60,
): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const th = (i / steps) * turns * 2 * Math.PI;
    const r = r0 * Math.exp(-b * th);
    const a = start + dir * th;
    out.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return out;
};

const circle = (cx: number, cy: number, r: number, n = 36): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * 2 * Math.PI;
    out.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return out;
};

/** A body from Figma, scaled to `height` and set on the origin, its top in the middle. */
const body = (paths: string[], box: Pt, height: number): Pt[][] => {
  const sc = height / box[1];
  return paths.flatMap((d) =>
    samplePath(d).map((poly) =>
      poly.map(([x, y]): Pt => [(x - box[0] / 2) * sc, (y - box[1]) * sc]),
    ),
  );
};

const flat = (pts: Pt[]): number[] => pts.flat();

/**
 * Leans everything by `angle` about the foot, then scales it so the
 * tallest point is 1 high: local units.
 */
const finish = (
  ink: Pt[][],
  paper: Pt[][],
  rings: number[][],
  angle: number,
  halfWidth: number,
): Shape => {
  const c = Math.cos(angle);
  const s = Math.sin(angle);
  const turn = (p: Pt): Pt => [p[0] * c - p[1] * s, p[0] * s + p[1] * c];
  const inkT = ink.map((poly) => poly.map(turn));
  const paperT = paper.map((poly) => poly.map(turn));
  let top = 0;
  for (const poly of inkT) for (const p of poly) top = Math.max(top, -p[1]);
  const k = 1 / top;
  return {
    ink: inkT.map((poly) => flat(poly.map(([x, y]) => [x * k, y * k]))),
    paper: paperT.map((poly) => flat(poly.map(([x, y]) => [x * k, y * k]))),
    rings: rings.map(([cx, cy, r, w]) => {
      const [tx, ty] = turn([cx, cy]);
      return [tx * k, ty * k, r * k, w * k];
    }),
    halfWidth: halfWidth * k,
  };
};

/** Every shape is drawn in the units of the sketch (px of a 370-tall cello) and normalised. */
const LEAN = (8 * Math.PI) / 180;

export const celloShape = (): Shape => {
  const [outline, ...holes] = body(CELLO_BODY, CELLO_BOX, 222);
  // The neck: a stem up from the top of the body, bending a touch, and
  // curling over at the top.
  const neck = bezier([0, -218], [0, -278], [3, -318], [14, -356]);
  const curl = spiral(44, -362, 32, 1.4, 0.2, -1, Math.PI);
  const stem = ribbon(neck.concat(curl.slice(1)), 13, 2.5);
  return finish([outline, stem], holes, [], LEAN, 70);
};

export const guitarShape = (): Shape => {
  const [outline] = body(GUITAR_BODY, GUITAR_BOX, 214);
  const neck = bezier([0, -210], [0, -262], [-4, -310], [-16, -350]);
  const curl = spiral(-44, -356, 30, 1.4, 0.2, 1, 0);
  const stem = ribbon(neck.concat(curl.slice(1)), 12, 2.5);
  return finish([outline, stem], [circle(0, -92, 19)], [], -LEAN, 72);
};

export const drumsShape = (): Shape => {
  const ink: Pt[][] = [];
  const rings: number[][] = [];
  // A cymbal: a thin tilted disc on a stem leaning out to the left.
  ink.push(
    ribbon(bezier([-96, 0], [-98, -70], [-120, -130], [-104, -192]), 4.5, 2.5),
  );
  const disc: Pt[] = [];
  for (let i = 0; i < 40; i++) {
    const a = (i / 40) * 2 * Math.PI;
    const x = 40 * Math.cos(a);
    const y = 5 * Math.sin(a);
    const r = -0.25;
    disc.push([
      -104 + x * Math.cos(r) - y * Math.sin(r),
      -194 + x * Math.sin(r) + y * Math.cos(r),
    ]);
  }
  ink.push(disc);
  // A stem rising behind the drum on the right and arching over it like a
  // crook; three small drums hang from it, each with its rim.
  const crook = bezier([84, 0], [90, -150], [100, -262], [-6, -268], 60);
  ink.push(ribbon(crook, 5, 2.5));
  for (const [t, r] of [
    [0.6, 19],
    [0.78, 15],
    [0.95, 12],
  ]) {
    const [x, y] = crook[Math.round(t * 60)];
    ink.push(
      ribbon(
        [
          [x, y],
          [x + 2, y + 22],
        ],
        2,
        2,
      ),
    );
    ink.push(circle(x + 2, y + 22 + r, r));
    rings.push([x + 2, y + 22 + r, r * 0.66, 1.8]);
  }
  // The big drum, plain, on two short legs.
  ink.push(
    ribbon(
      [
        [-30, -30],
        [-40, 2],
      ],
      5,
      3,
    ),
  );
  ink.push(
    ribbon(
      [
        [30, -30],
        [40, 2],
      ],
      5,
      3,
    ),
  );
  ink.push(circle(0, -80, 64, 48));
  return finish(ink, [], rings, 0, 110);
};

